/// The direct three-byte comparison in the stage-3 `n >= 2` branch.
pub const STAGE3_DIRECT_SLOT: &[u8] = DAT_0047DF14;

/// Compare the exact fixed byte count used by the original helper.  A Rust
/// caller may omit the trailing NUL; the missing byte is treated as zero,
/// matching a normal NUL-terminated record slot.
pub fn eq_fixed(actual: &[u8], expected: &[u8]) -> bool {
    (0..expected.len()).all(|i| actual.get(i).copied().unwrap_or(0) == expected[i])
}

/// Compare two internal KPS strings with the original 2-byte stepping and
/// NUL termination.  The stepping is observable only in malformed input; for
/// normal records this is exact NUL-terminated equality.
pub fn eq_kps_z(actual: &[u8], expected: &[u8]) -> bool {
    let mut i = 0usize;
    loop {
        let a0 = actual.get(i).copied().unwrap_or(0);
        let b0 = expected.get(i).copied().unwrap_or(0);
        if a0 != b0 {
            return false;
        }
        if a0 == 0 {
            return true;
        }

        let a1 = actual.get(i + 1).copied().unwrap_or(0);
        let b1 = expected.get(i + 1).copied().unwrap_or(0);
        if a1 != b1 {
            return false;
        }
        if a1 == 0 {
            return true;
        }
        i += 2;
    }
}

pub fn stage3_type_a_matches(actual: &[u8]) -> bool {
    STAGE3_TYPE_A_TABLE
        .iter()
        .any(|item| eq_kps_z(actual, item))
}

pub fn stage3_sentence_matches(actual: &[u8]) -> bool {
    STAGE3_SENTENCE_TABLE
        .iter()
        .any(|item| eq_kps_z(actual, item))
}

pub fn stage3_pair_matches(first: &[u8], second: &[u8]) -> bool {
    STAGE3_PAIR_TABLE
        .iter()
        .any(|(lhs, rhs)| eq_kps_z(first, lhs) && eq_kps_z(second, rhs))
}
